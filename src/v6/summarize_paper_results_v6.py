def write_svg(path, width, height, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    svg = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" fill="white"/>',
        '<style>text{font-family:Arial,sans-serif;font-size:12px;fill:#222}.title{font-size:18px;font-weight:700}.axis{stroke:#333;stroke-width:1}.grid{stroke:#ddd;stroke-width:1}.missing{fill:#666;font-size:14px}</style>',
        *body,
        "</svg>",
    ]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(svg) + "\n")


def numeric(value):
    if value == "" or value is None:
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def value_domain(values):
    valid = [v for v in values if v is not None]
    if not valid:
        return 0.0, 1.0
    lo = min(min(valid), 0.0)
    hi = max(max(valid), 0.0)
    if abs(hi - lo) < 1e-9:
        pad = max(abs(hi), 1.0) * 0.1
        lo -= pad
        hi += pad
    else:
        pad = (hi - lo) * 0.12
        lo -= pad
        hi += pad
    return lo, hi


def y_for_value(value, lo, hi, margin_t, plot_h):
    return margin_t + plot_h - ((value - lo) / (hi - lo)) * plot_h


def write_fixed_mode_svg(path, fixed_rows):
    width, height = 900, 420
    margin_l, margin_r, margin_t, margin_b = 70, 30, 48, 82
    plot_w = width - margin_l - margin_r
    plot_h = height - margin_t - margin_b
    colors = {"worm": "#4c78a8", "snake": "#f58518", "mixed": "#54a24b"}
    values = [numeric(r["rl_speed_mm_s"]) for r in fixed_rows]
    min_v, max_v = value_domain(values)
    terrain_w = plot_w / len(PAPER_TERRAINS)
    bar_w = terrain_w / 5.0
    y_zero = y_for_value(0.0, min_v, max_v, margin_t, plot_h)
    body = [
        f'<text class="title" x="{width/2}" y="28" text-anchor="middle">Fixed mode RL speed by terrain</text>',
        f'<line class="axis" x1="{margin_l}" y1="{y_zero:.1f}" x2="{margin_l + plot_w}" y2="{y_zero:.1f}"/>',
        f'<line class="axis" x1="{margin_l}" y1="{margin_t}" x2="{margin_l}" y2="{margin_t + plot_h}"/>',
        f'<text x="18" y="{margin_t + plot_h/2}" transform="rotate(-90 18 {margin_t + plot_h/2})" text-anchor="middle">speed (mm/s)</text>',
    ]
    for i in range(5):
        y_val = min_v + (max_v - min_v) * i / 4
        y = y_for_value(y_val, min_v, max_v, margin_t, plot_h)
        body.append(f'<line class="grid" x1="{margin_l}" y1="{y:.1f}" x2="{margin_l + plot_w}" y2="{y:.1f}"/>')
        body.append(f'<text x="{margin_l - 8}" y="{y + 4:.1f}" text-anchor="end">{y_val:.1f}</text>')

    has_data = False
    for ti, terrain in enumerate(PAPER_TERRAINS):
        cx = margin_l + terrain_w * (ti + 0.5)
        body.append(f'<text x="{cx:.1f}" y="{height - 38}" text-anchor="middle">{terrain}</text>')
        for mi, mode in enumerate(PAPER_MODES):
            row = next(r for r in fixed_rows
                       if r["terrain"] == terrain and r["mode"] == mode)
            value = numeric(row["rl_speed_mm_s"])
            x = cx + (mi - 1) * (bar_w * 1.15) - bar_w / 2
            if value is None:
                body.append(f'<rect x="{x:.1f}" y="{y_zero - 2:.1f}" width="{bar_w:.1f}" height="4" fill="#ddd"/>')
            else:
                has_data = True
                y = y_for_value(value, min_v, max_v, margin_t, plot_h)
                h = abs(y_zero - y)
                y = min(y, y_zero)
                body.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{bar_w:.1f}" height="{h:.1f}" fill="{colors[mode]}"/>')
                body.append(f'<text x="{x + bar_w/2:.1f}" y="{y - 4:.1f}" text-anchor="middle">{value:.1f}</text>')

    legend_x = width - 260
    for i, mode in enumerate(PAPER_MODES):
        x = legend_x + i * 84
        body.append(f'<rect x="{x}" y="18" width="14" height="14" fill="{colors[mode]}"/>')
        body.append(f'<text x="{x + 20}" y="30">{mode}</text>')
    if not has_data:
        body.append(f'<text class="missing" x="{width/2}" y="{height/2}" text-anchor="middle">No RL evaluation data yet</text>')
    write_svg(path, width, height, body)


def write_blend_scan_svg(path, scan_rows):
    width, height = 900, 420
    margin_l, margin_r, margin_t, margin_b = 70, 35, 48, 70
    plot_w = width - margin_l - margin_r
    plot_h = height - margin_t - margin_b
    colors = {"flat": "#4c78a8", "sand": "#b279a2", "slope": "#e45756"}
    valid = [
        r for r in scan_rows
        if numeric(r.get("gait_blend")) is not None
        and numeric(r.get("mean_speed_mm_s")) is not None
    ]
    min_v, max_v = value_domain([
        numeric(r["mean_speed_mm_s"]) for r in valid
    ])
    y_zero = y_for_value(0.0, min_v, max_v, margin_t, plot_h)
    body = [
        f'<text class="title" x="{width/2}" y="28" text-anchor="middle">Speed versus gait_blend</text>',
        f'<line class="axis" x1="{margin_l}" y1="{y_zero:.1f}" x2="{margin_l + plot_w}" y2="{y_zero:.1f}"/>',
        f'<line class="axis" x1="{margin_l}" y1="{margin_t}" x2="{margin_l}" y2="{margin_t + plot_h}"/>',
        f'<text x="{margin_l + plot_w/2}" y="{height - 20}" text-anchor="middle">gait_blend (0 = worm, 1 = snake)</text>',
        f'<text x="18" y="{margin_t + plot_h/2}" transform="rotate(-90 18 {margin_t + plot_h/2})" text-anchor="middle">speed (mm/s)</text>',
    ]
    for i in range(5):
        x_val = i / 4
        x = margin_l + x_val * plot_w
        body.append(f'<line class="grid" x1="{x:.1f}" y1="{margin_t}" x2="{x:.1f}" y2="{margin_t + plot_h}"/>')
        body.append(f'<text x="{x:.1f}" y="{margin_t + plot_h + 18}" text-anchor="middle">{x_val:.2f}</text>')
        y_val = min_v + (max_v - min_v) * i / 4
        y = y_for_value(y_val, min_v, max_v, margin_t, plot_h)
        body.append(f'<line class="grid" x1="{margin_l}" y1="{y:.1f}" x2="{margin_l + plot_w}" y2="{y:.1f}"/>')
        body.append(f'<text x="{margin_l - 8}" y="{y + 4:.1f}" text-anchor="end">{y_val:.1f}</text>')

    if not valid:
        body.append(f'<text class="missing" x="{width/2}" y="{height/2}" text-anchor="middle">No blend scan data yet</text>')
    for terrain in PAPER_TERRAINS:
        rows = sorted(
            [r for r in valid if r["terrain"] == terrain],
            key=lambda r: numeric(r["gait_blend"]))
        if not rows:
            continue
        points = []
        for row in rows:
            x = margin_l + numeric(row["gait_blend"]) * plot_w
            y = y_for_value(
                numeric(row["mean_speed_mm_s"]), min_v, max_v,
                margin_t, plot_h)
            points.append((x, y))
        d = " ".join(f"{x:.1f},{y:.1f}" for x, y in points)
        body.append(f'<polyline points="{d}" fill="none" stroke="{colors[terrain]}" stroke-width="3"/>')
        for x, y in points:
            body.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="4" fill="{colors[terrain]}"/>')
    legend_x = width - 255
    for i, terrain in enumerate(PAPER_TERRAINS):
        x = legend_x + i * 78
        body.append(f'<line x1="{x}" y1="25" x2="{x + 18}" y2="25" stroke="{colors[terrain]}" stroke-width="3"/>')
        body.append(f'<text x="{x + 24}" y="29">{terrain}</text>')
    write_svg(path, width, height, body)


def fmt(value):
    if value == "" or value is None:
        return ""
    try:
        return f"{float(value):.3f}"
    except (TypeError, ValueError):
        return str(value)


