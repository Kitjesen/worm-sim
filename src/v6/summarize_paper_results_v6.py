"""
Summarize Worm V6 paper experiment outputs into CSV/Markdown artifacts.

Inputs are generated by:
  - eval_v6.py for fixed worm/snake/mixed deployable RL runs
  - scan_gait_blend_v6.py for continuous gait_blend scans
  - optimize_speed.py for CMA-ES open-loop baselines
"""

import argparse
import csv
import json
import os

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.normpath(os.path.join(SCRIPT_DIR, "..", ".."))

PAPER_TERRAINS = ("flat", "sand", "slope")
PAPER_MODES = ("worm", "snake", "mixed")
MODE_TO_CMAES = {
    "worm": "peristaltic",
    "snake": "serpentine",
    "mixed": "full",
}


def read_json(path):
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def rl_metrics_path(terrain, mode):
    return os.path.join(PROJECT_ROOT, "runs", f"worm_v6_ppo_{terrain}_{mode}",
                        "eval_metrics.json")


def rl_robust_metrics_path(terrain, mode):
    return os.path.join(PROJECT_ROOT, "runs", f"worm_v6_ppo_{terrain}_{mode}",
                        "eval_metrics_robust.json")


def cmaes_path(terrain, mode):
    return os.path.join(PROJECT_ROOT, "runs",
                        f"cmaes_{terrain}_{MODE_TO_CMAES[mode]}",
                        "best_gait.json")


def scan_path(terrain, policy_mode):
    return os.path.join(PROJECT_ROOT, "runs",
                        f"worm_v6_blend_scan_{terrain}_{policy_mode}",
                        "scan_results.json")


def collect_fixed_mode_rows():
    rows = []
    for terrain in PAPER_TERRAINS:
        for mode in PAPER_MODES:
            rl = read_json(rl_metrics_path(terrain, mode))
            robust = read_json(rl_robust_metrics_path(terrain, mode))
            cmaes = read_json(cmaes_path(terrain, mode))
            rows.append({
                "terrain": terrain,
                "mode": mode,
                "rl_speed_mm_s": value_or_blank(rl, "mean_speed_mm_s"),
                "rl_lateral_drift_mm": value_or_blank(
                    rl, "mean_lateral_drift_mm"),
                "rl_action_l2_per_m": value_or_blank(
                    rl, "mean_action_l2_per_m"),
                "rl_path_efficiency": value_or_blank(
                    rl, "mean_path_efficiency"),
                "rl_slip_proxy": value_or_blank(rl, "mean_slip_proxy"),
                "rl_success_rate": value_or_blank(rl, "success_rate"),
                "rl_propulsion_efficiency_m_per_action_l2": value_or_blank(
                    rl, "mean_propulsion_efficiency_m_per_action_l2"),
                "rl_termination_rate": value_or_blank(rl, "termination_rate"),
                "robust_speed_mm_s": value_or_blank(robust, "mean_speed_mm_s"),
                "robust_success_rate": value_or_blank(robust, "success_rate"),
                "robust_slip_proxy": value_or_blank(
                    robust, "mean_slip_proxy"),
                "robust_termination_rate": value_or_blank(
                    robust, "termination_rate"),
                "robust_status": "done" if robust is not None else "missing",
                "cmaes_speed_mm_s": value_or_blank(cmaes, "best_speed_mm_s"),
                "rl_status": "done" if rl is not None else "missing",
                "cmaes_status": "done" if cmaes is not None else "missing",
            })
    return rows


def collect_scan_rows(policy_mode):
    rows = []
    for terrain in PAPER_TERRAINS:
        data = read_json(scan_path(terrain, policy_mode))
        if not data:
            continue
        for item in data:
            rows.append({
                "terrain": item.get("terrain", terrain),
                "policy_mode": item.get("policy_mode", policy_mode),
                "gait_blend": item.get("gait_blend"),
                "mean_speed_mm_s": item.get("mean_speed_mm_s"),
                "mean_lateral_drift_mm": item.get("mean_lateral_drift_mm"),
                "mean_action_l2_per_m": item.get("mean_action_l2_per_m"),
                "mean_path_efficiency": item.get("mean_path_efficiency"),
                "mean_slip_proxy": item.get("mean_slip_proxy"),
                "mean_propulsion_efficiency_m_per_action_l2": item.get(
                    "mean_propulsion_efficiency_m_per_action_l2"),
                "success_rate": item.get("success_rate"),
                "termination_rate": item.get("termination_rate"),
                "model_path": item.get("model_path"),
            })
    return rows


def value_or_blank(data, key):
    if data is None:
        return ""
    value = data.get(key)
    return "" if value is None else value


def write_csv(path, rows, fields):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def best_scan_rows(scan_rows):
    best = {}
    for row in scan_rows:
        terrain = row["terrain"]
        speed = row.get("mean_speed_mm_s")
        if speed is None:
            continue
        if terrain not in best or speed > best[terrain].get("mean_speed_mm_s", -1e9):
            best[terrain] = row
    return [best[t] for t in PAPER_TERRAINS if t in best]


def mean(values):
    values = [v for v in values if v is not None]
    if not values:
        return None
    return sum(values) / len(values)


def blend_label(blend):
    value = numeric(blend)
    if value is None:
        return "unknown"
    if abs(value - 0.0) <= 1e-9:
        return "worm"
    if abs(value - 1.0) <= 1e-9:
        return "snake"
    return "mixed"


def best_row_by_speed(rows, speed_key):
    candidates = [
        row for row in rows
        if numeric(row.get(speed_key)) is not None
    ]
    if not candidates:
        return None
    return max(candidates, key=lambda row: numeric(row.get(speed_key)))


def best_row_by_lowest(rows, key):
    candidates = [
        row for row in rows
        if numeric(row.get(key)) is not None
    ]
    if not candidates:
        return None
    return min(candidates, key=lambda row: numeric(row.get(key)))


def build_claim_report(fixed_rows, scan_rows, best_rows):
    fixed_averages = []
    for mode in PAPER_MODES:
        rows = [row for row in fixed_rows if row["mode"] == mode]
        fixed_averages.append({
            "mode": mode,
            "avg_speed_mm_s": mean([
                numeric(row.get("rl_speed_mm_s")) for row in rows
            ]),
            "avg_success_rate": mean([
                numeric(row.get("rl_success_rate")) for row in rows
            ]),
            "avg_termination_rate": mean([
                numeric(row.get("rl_termination_rate")) for row in rows
            ]),
        })

    best_single_speed = best_row_by_speed(
        fixed_averages, "avg_speed_mm_s")
    best_single_success = best_row_by_speed(
        fixed_averages, "avg_success_rate")
    best_single_stability = best_row_by_lowest(
        fixed_averages, "avg_termination_rate")
    adaptive = {
        "policy": "random_best_blend_per_terrain",
        "avg_speed_mm_s": mean([
            numeric(row.get("mean_speed_mm_s")) for row in best_rows
        ]),
        "avg_success_rate": mean([
            numeric(row.get("success_rate")) for row in best_rows
        ]),
        "avg_termination_rate": mean([
            numeric(row.get("termination_rate")) for row in best_rows
        ]),
    }

    terrain_rows = []
    for terrain in PAPER_TERRAINS:
        fixed_best = best_row_by_speed(
            [row for row in fixed_rows if row["terrain"] == terrain],
            "rl_speed_mm_s")
        scan_best = best_row_by_speed(
            [row for row in scan_rows if row["terrain"] == terrain],
            "mean_speed_mm_s")
        entry = {
            "terrain": terrain,
            "fixed_best_mode": fixed_best.get("mode") if fixed_best else None,
            "fixed_best_speed_mm_s": (
                numeric(fixed_best.get("rl_speed_mm_s"))
                if fixed_best else None),
            "scan_best_gait_blend": (
                numeric(scan_best.get("gait_blend"))
                if scan_best else None),
            "scan_best_label": (
                blend_label(scan_best.get("gait_blend"))
                if scan_best else None),
            "scan_best_speed_mm_s": (
                numeric(scan_best.get("mean_speed_mm_s"))
                if scan_best else None),
            "scan_best_success_rate": (
                numeric(scan_best.get("success_rate"))
                if scan_best else None),
        }
        if (entry["scan_best_speed_mm_s"] is not None
                and entry["fixed_best_speed_mm_s"] is not None):
            entry["scan_vs_fixed_best_delta_mm_s"] = (
                entry["scan_best_speed_mm_s"]
                - entry["fixed_best_speed_mm_s"])
        else:
            entry["scan_vs_fixed_best_delta_mm_s"] = None
        terrain_rows.append(entry)

    speed_delta = None
    if (adaptive["avg_speed_mm_s"] is not None
            and best_single_speed
            and best_single_speed["avg_speed_mm_s"] is not None):
        speed_delta = (
            adaptive["avg_speed_mm_s"]
            - best_single_speed["avg_speed_mm_s"])

    success_delta = None
    if (adaptive["avg_success_rate"] is not None
            and best_single_success
            and best_single_success["avg_success_rate"] is not None):
        success_delta = (
            adaptive["avg_success_rate"]
            - best_single_success["avg_success_rate"])

    termination_delta = None
    if (adaptive["avg_termination_rate"] is not None
            and best_single_stability
            and best_single_stability["avg_termination_rate"] is not None):
        termination_delta = (
            adaptive["avg_termination_rate"]
            - best_single_stability["avg_termination_rate"])

    speed_supported = speed_delta is not None and speed_delta > 0.0
    success_supported = success_delta is not None and success_delta >= 0.0
    termination_supported = (
        termination_delta is not None and termination_delta <= 0.0)
    if speed_supported and (success_supported or termination_supported):
        goal3_status = "supported"
    elif speed_supported or success_supported or termination_supported:
        goal3_status = "mixed"
    else:
        goal3_status = "not_supported"

    claims = [
        {
            "claim": (
                "Continuous gait_blend exposes terrain-dependent mode "
                "preferences."),
            "status": "supported" if len(terrain_rows) == len(PAPER_TERRAINS)
            else "incomplete",
            "evidence": terrain_rows,
        },
        {
            "claim": (
                "Adaptive best-blend random policy improves cross-terrain "
                "average speed over the best single fixed mode."),
            "status": "supported" if speed_supported else "not_supported",
            "adaptive_avg_speed_mm_s": adaptive["avg_speed_mm_s"],
            "best_single_mode": (
                best_single_speed.get("mode") if best_single_speed else None),
            "best_single_avg_speed_mm_s": (
                best_single_speed.get("avg_speed_mm_s")
                if best_single_speed else None),
            "delta_mm_s": speed_delta,
        },
        {
            "claim": (
                "Adaptive best-blend random policy improves or preserves "
                "cross-terrain success rate versus the best single fixed mode."),
            "status": "supported" if success_supported else "not_supported",
            "adaptive_avg_success_rate": adaptive["avg_success_rate"],
            "best_single_mode": (
                best_single_success.get("mode") if best_single_success
                else None),
            "best_single_avg_success_rate": (
                best_single_success.get("avg_success_rate")
                if best_single_success else None),
            "delta_success_rate": success_delta,
        },
        {
            "claim": (
                "Adaptive best-blend random policy improves or preserves "
                "cross-terrain termination rate versus the most stable "
                "single fixed mode."),
            "status": "supported" if termination_supported
            else "not_supported",
            "adaptive_avg_termination_rate": adaptive[
                "avg_termination_rate"],
            "best_single_mode": (
                best_single_stability.get("mode") if best_single_stability
                else None),
            "best_single_avg_termination_rate": (
                best_single_stability.get("avg_termination_rate")
                if best_single_stability else None),
            "delta_termination_rate": termination_delta,
            "interpretation": "negative_or_zero_is_better",
        },
    ]

    cautions = []
    for entry in terrain_rows:
        if (entry.get("scan_vs_fixed_best_delta_mm_s") is not None
                and entry["scan_vs_fixed_best_delta_mm_s"] < 0.0):
            cautions.append(
                f"{entry['terrain']}: best continuous random-policy blend "
                "does not beat the best terrain-specific fixed policy speed.")
    if goal3_status == "mixed":
        cautions.append(
            "Goal 3 is speed-supported but not fully success-supported in "
            "the current artifacts.")
    elif goal3_status == "supported" and not success_supported:
        cautions.append(
            "Success rate is not improved; frame Goal 3 around average "
            "speed and termination stability, not success.")

    return {
        "format_version": 1,
        "inputs": {
            "fixed_mode_summary": "fixed_mode_summary.csv",
            "blend_scan_summary": "blend_scan_summary.csv",
            "best_blend_by_terrain": "best_blend_by_terrain.csv",
        },
        "terrain_mode_selection": terrain_rows,
        "fixed_single_mode_averages": fixed_averages,
        "adaptive_best_blend_average": adaptive,
        "goal3_status": goal3_status,
        "claim_assessments": claims,
        "cautions": cautions,
    }


def write_claims(path_json, path_md, report):
    os.makedirs(os.path.dirname(path_json), exist_ok=True)
    with open(path_json, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)

    lines = [
        "# Worm V6 Paper Claim Analysis",
        "",
        "## Terrain Mode Selection",
        "",
        "| Terrain | Best fixed mode | Fixed speed mm/s | Best gait_blend | Blend label | Blend speed mm/s | Delta vs fixed |",
        "| --- | --- | ---: | ---: | --- | ---: | ---: |",
    ]
    for row in report["terrain_mode_selection"]:
        lines.append(
            f"| {row['terrain']} | {row['fixed_best_mode']} | "
            f"{fmt(row['fixed_best_speed_mm_s'])} | "
            f"{fmt(row['scan_best_gait_blend'])} | "
            f"{row['scan_best_label']} | "
            f"{fmt(row['scan_best_speed_mm_s'])} | "
            f"{fmt(row['scan_vs_fixed_best_delta_mm_s'])} |")

    lines.extend([
        "",
        "## Cross-Terrain Averages",
        "",
        "| Policy | Speed mm/s | Success | Termination |",
        "| --- | ---: | ---: | ---: |",
    ])
    for row in report["fixed_single_mode_averages"]:
        lines.append(
            f"| fixed {row['mode']} | {fmt(row['avg_speed_mm_s'])} | "
            f"{fmt(row['avg_success_rate'])} | "
            f"{fmt(row['avg_termination_rate'])} |")
    adaptive = report["adaptive_best_blend_average"]
    lines.append(
        f"| adaptive best blend | {fmt(adaptive['avg_speed_mm_s'])} | "
        f"{fmt(adaptive['avg_success_rate'])} | "
        f"{fmt(adaptive['avg_termination_rate'])} |")

    lines.extend([
        "",
        "## Claim Assessments",
        "",
        "| Claim | Status |",
        "| --- | --- |",
    ])
    for claim in report["claim_assessments"]:
        lines.append(f"| {claim['claim']} | {claim['status']} |")

    if report["cautions"]:
        lines.extend(["", "## Cautions", ""])
        for caution in report["cautions"]:
            lines.append(f"- {caution}")

    with open(path_md, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


